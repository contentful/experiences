import { describe, expect, expectTypeOf, it } from 'vitest';
import type { ContentfulViewDelivery } from '@contentful/experience-delivery';
import type { ExperienceDeliveryDiagnostic } from '@contentful/experiences-sdk-core';
import {
  toExperiencePayload,
  toExperiencePayloadFromDestination,
} from './to-experience-payload.js';

describe('Delivery payload diagnostics compatibility', () => {
  it('matches the supported fields of the generated by-ID ResolutionError', () => {
    expectTypeOf<
      Readonly<Pick<ContentfulViewDelivery.ResolutionError, 'fieldPath' | 'message'>>
    >().toEqualTypeOf<ExperienceDeliveryDiagnostic>();
    expectTypeOf<
      ContentfulViewDelivery.HydratedExperienceView['errors'][number]
    >().toEqualTypeOf<ContentfulViewDelivery.ResolutionError>();
  });

  it('preserves raw by-ID errors for Core to normalize', () => {
    const response: ContentfulViewDelivery.HydratedExperienceView = {
      sys: {
        id: 'experience',
        type: 'Experience',
        space: { sys: { type: 'Link', linkType: 'Space', id: 'space' } },
        environment: { sys: { type: 'Link', linkType: 'Environment', id: 'master' } },
        experienceTemplate: {
          sys: {
            type: 'ResourceLink',
            linkType: 'Contentful:ExperienceTemplate',
            urn: 'crn:contentful:::experience:spaces/space/environments/master/experienceTemplates/page',
          },
        },
        createdAt: '2026-10-23T00:00:00.000Z',
        updatedAt: '2026-10-23T00:00:00.000Z',
        createdBy: { sys: { type: 'Link', linkType: 'User', id: 'user' } },
        updatedBy: { sys: { type: 'Link', linkType: 'User', id: 'user' } },
      },
      nodes: [],
      errors: [{ fieldPath: 'nodes[0].title', message: 'Missing title', originalError: {} }],
    };

    const payload = toExperiencePayload(response);

    expect(payload).toBe(response);
    expect(payload.errors).toBe(response.errors);
    expect(payload.errors).toEqual(response.errors);
  });

  it('preserves broader destination error records without claiming their schema', () => {
    const experience: ContentfulViewDelivery.HydratedExperience = {
      sys: { id: 'experience' },
      nodes: [],
      errors: [
        { fieldPath: 'nodes[0].title', message: 'Missing title', originalError: {} },
        { unsupported: 'destination-specific error' },
      ],
    };

    const payload = toExperiencePayloadFromDestination(experience);

    expect(payload).toBe(experience);
    expect(payload.errors).toBe(experience.errors);
    expect(payload.errors).toEqual(experience.errors);
  });
});
